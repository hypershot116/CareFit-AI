import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_markdown/flutter_markdown.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:carefit_ai/theme/app_theme.dart';
import 'package:carefit_ai/models/user_profile.dart';
import 'package:carefit_ai/services/groq_service.dart';
import 'package:carefit_ai/screens/home_screen.dart';

class ResultScreen extends StatefulWidget {
  final UserProfile profile;
  const ResultScreen({super.key, required this.profile});

  @override
  State<ResultScreen> createState() => _ResultScreenState();
}

class _ResultScreenState extends State<ResultScreen> {
  late Future<String> _planFuture;
  final _groqService = GroqService();

  @override
  void initState() {
    super.initState();
    _planFuture = _groqService.generateFitnessPlan(widget.profile);
  }

  void _regenerate() {
    setState(() {
      _planFuture = _groqService.generateFitnessPlan(widget.profile);
    });
  }

  void _copyToClipboard(String text) {
    Clipboard.setData(ClipboardData(text: text));
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: const Text('Plan copied to clipboard!'),
        backgroundColor: AppTheme.accent,
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      ),
    );
  }

  Future<void> _downloadPdf(String planText) async {
    final pdf = pw.Document();

    // Clean markdown symbols for PDF
    final lines = planText.split('\n');

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  'CareFit AI',
                  style: pw.TextStyle(
                    fontSize: 20,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.deepPurple,
                  ),
                ),
                pw.Text(
                  'Personalized Fitness Plan',
                  style: const pw.TextStyle(
                    fontSize: 11,
                    color: PdfColors.grey600,
                  ),
                ),
              ],
            ),
            pw.Divider(color: PdfColors.deepPurple200),
            pw.SizedBox(height: 4),
          ],
        ),
        footer: (context) => pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'Generated by CareFit AI',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey500),
            ),
          ],
        ),
        build: (context) {
          List<pw.Widget> widgets = [];
          for (final line in lines) {
            if (line.trim().isEmpty) {
              widgets.add(pw.SizedBox(height: 6));
            } else if (line.startsWith('## ')) {
              widgets.add(pw.SizedBox(height: 12));
              widgets.add(
                pw.Text(
                  line.replaceAll('## ', ''),
                  style: pw.TextStyle(
                    fontSize: 16,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.deepPurple,
                  ),
                ),
              );
              widgets.add(pw.Divider(color: PdfColors.deepPurple100));
            } else if (line.startsWith('### ')) {
              widgets.add(pw.SizedBox(height: 8));
              widgets.add(
                pw.Text(
                  line.replaceAll('### ', ''),
                  style: pw.TextStyle(
                    fontSize: 13,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.teal700,
                  ),
                ),
              );
            } else if (line.startsWith('# ')) {
              widgets.add(pw.SizedBox(height: 16));
              widgets.add(
                pw.Text(
                  line.replaceAll('# ', ''),
                  style: pw.TextStyle(
                    fontSize: 20,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.deepPurple900,
                  ),
                ),
              );
            } else if (line.startsWith('- ') || line.startsWith('* ')) {
              final text = line.replaceFirst(RegExp(r'^[-*]\s'), '');
              widgets.add(
                pw.Padding(
                  padding: const pw.EdgeInsets.only(left: 16, bottom: 3),
                  child: pw.Row(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        '- ',
                        style: pw.TextStyle(
                          color: PdfColors.deepPurple,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                      pw.Expanded(
                        child: pw.Text(
                          text.replaceAll('**', '').replaceAll('*', ''),
                          style: const pw.TextStyle(
                            fontSize: 11,
                            color: PdfColors.grey800,
                          ),
                        ),
                      ),
                    ],
                  ),
                ),
              );
            } else if (line.startsWith('**') && line.endsWith('**')) {
              widgets.add(
                pw.Text(
                  line.replaceAll('**', ''),
                  style: pw.TextStyle(
                    fontWeight: pw.FontWeight.bold,
                    fontSize: 11,
                  ),
                ),
              );
            } else {
              widgets.add(
                pw.Text(
                  line.replaceAll('**', '').replaceAll('*', ''),
                  style: const pw.TextStyle(
                    fontSize: 11,
                    color: PdfColors.grey800,
                    lineSpacing: 1.4,
                  ),
                ),
              );
            }
          }
          return widgets;
        },
      ),
    );

    await Printing.sharePdf(
      bytes: await pdf.save(),
      filename: 'CareFit_AI_Plan.pdf',
    );
  }

  void _goHome() {
    Navigator.pushAndRemoveUntil(
      context,
      MaterialPageRoute(builder: (_) => const HomeScreen()),
      (route) => false,
    );
  }

  @override
  Widget build(BuildContext context) {
    return PopScope(
      canPop: false,
      onPopInvokedWithResult: (didPop, result) {
        if (!didPop) _goHome();
      },
      child: Scaffold(
        appBar: AppBar(
          title: const Text('Your Fitness Plan'),
          leading: IconButton(
            icon: const Icon(Icons.home_rounded),
            tooltip: 'Go to Home',
            onPressed: _goHome,
          ),
          actions: [
            FutureBuilder<String>(
              future: _planFuture,
              builder: (ctx, snap) => snap.hasData
                  ? IconButton(
                      icon: const Icon(Icons.copy_rounded),
                      tooltip: 'Copy plan',
                      onPressed: () => _copyToClipboard(snap.data!),
                    )
                  : const SizedBox(),
            ),
          ],
        ),
        body: FutureBuilder<String>(
          future: _planFuture,
          builder: (context, snapshot) {
            if (snapshot.connectionState == ConnectionState.waiting) {
              return _loadingState();
            }
            if (snapshot.hasError) {
              return _errorState(snapshot.error.toString());
            }
            if (snapshot.hasData) {
              return _resultState(snapshot.data!);
            }
            return const SizedBox();
          },
        ),
      ),
    );
  }

  Widget _loadingState() {
    return Center(
      child: Column(
        mainAxisAlignment: MainAxisAlignment.center,
        children: [
          Container(
            width: 80,
            height: 80,
            decoration: BoxDecoration(
              gradient: const LinearGradient(
                colors: [AppTheme.primary, AppTheme.accent],
              ),
              borderRadius: BorderRadius.circular(20),
            ),
            child: const Padding(
              padding: EdgeInsets.all(20),
              child: CircularProgressIndicator(
                color: Colors.white,
                strokeWidth: 3,
              ),
            ),
          ),
          const SizedBox(height: 24),
          const Text(
            'Generating your plan...',
            style: TextStyle(
              fontSize: 20,
              fontWeight: FontWeight.w600,
              color: AppTheme.textPrimary,
            ),
          ),
          const SizedBox(height: 8),
          const Text(
            'This may take 15–30 seconds',
            style: TextStyle(fontSize: 14, color: AppTheme.textSecondary),
          ),
        ],
      ),
    );
  }

  Widget _errorState(String error) {
    return Center(
      child: Padding(
        padding: const EdgeInsets.all(24),
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: AppTheme.error.withOpacity(0.15),
                borderRadius: BorderRadius.circular(20),
              ),
              child: const Icon(
                Icons.error_outline_rounded,
                color: AppTheme.error,
                size: 48,
              ),
            ),
            const SizedBox(height: 24),
            const Text(
              'Something went wrong',
              style: TextStyle(
                fontSize: 20,
                fontWeight: FontWeight.w600,
                color: AppTheme.textPrimary,
              ),
            ),
            const SizedBox(height: 8),
            Text(
              error.replaceAll('Exception: ', ''),
              textAlign: TextAlign.center,
              style: const TextStyle(
                fontSize: 14,
                color: AppTheme.textSecondary,
              ),
            ),
            const SizedBox(height: 32),
            Row(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                OutlinedButton.icon(
                  onPressed: _goHome,
                  icon: const Icon(Icons.home_rounded, size: 16),
                  label: const Text('Home'),
                  style: OutlinedButton.styleFrom(
                    foregroundColor: AppTheme.textSecondary,
                    side: const BorderSide(color: AppTheme.surface),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(12),
                    ),
                  ),
                ),
                const SizedBox(width: 12),
                ElevatedButton.icon(
                  onPressed: _regenerate,
                  icon: const Icon(Icons.refresh_rounded, color: Colors.white),
                  label: const Text(
                    'Try Again',
                    style: TextStyle(color: Colors.white),
                  ),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }

  Widget _resultState(String plan) {
    return Column(
      children: [
        // Banner
        Container(
          width: double.infinity,
          padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 14),
          decoration: BoxDecoration(
            gradient: LinearGradient(
              colors: [
                AppTheme.primary.withOpacity(0.2),
                AppTheme.accent.withOpacity(0.1),
              ],
            ),
            border: Border(
              bottom: BorderSide(color: AppTheme.primary.withOpacity(0.2)),
            ),
          ),
          child: Row(
            children: [
              Container(
                padding: const EdgeInsets.all(8),
                decoration: BoxDecoration(
                  color: AppTheme.primary.withOpacity(0.2),
                  borderRadius: BorderRadius.circular(10),
                ),
                child: const Icon(
                  Icons.auto_awesome_rounded,
                  color: AppTheme.primary,
                  size: 18,
                ),
              ),
              const SizedBox(width: 12),
              const Expanded(
                child: Text(
                  'Your personalized plan is ready!',
                  style: TextStyle(
                    fontSize: 14,
                    fontWeight: FontWeight.w600,
                    color: AppTheme.textPrimary,
                  ),
                ),
              ),
            ],
          ),
        ),
        // Plan content
        Expanded(
          child: Markdown(
            data: plan,
            padding: const EdgeInsets.all(20),
            styleSheet: MarkdownStyleSheet(
              h1: const TextStyle(
                fontSize: 22,
                fontWeight: FontWeight.w700,
                color: AppTheme.textPrimary,
              ),
              h2: const TextStyle(
                fontSize: 18,
                fontWeight: FontWeight.w700,
                color: AppTheme.primary,
              ),
              h3: const TextStyle(
                fontSize: 16,
                fontWeight: FontWeight.w600,
                color: AppTheme.accent,
              ),
              p: const TextStyle(
                fontSize: 14,
                color: AppTheme.textSecondary,
                height: 1.6,
              ),
              strong: const TextStyle(
                color: AppTheme.textPrimary,
                fontWeight: FontWeight.w600,
              ),
              listBullet: const TextStyle(color: AppTheme.primary),
              code: const TextStyle(
                backgroundColor: Color(0xFF1A1A2E),
                color: AppTheme.accent,
                fontSize: 13,
              ),
              codeblockDecoration: BoxDecoration(
                color: AppTheme.surface,
                borderRadius: BorderRadius.circular(8),
              ),
            ),
          ),
        ),
        // Bottom buttons
        Container(
          padding: const EdgeInsets.all(16),
          decoration: BoxDecoration(
            color: AppTheme.background,
            border: Border(
              top: BorderSide(color: AppTheme.surface.withOpacity(0.5)),
            ),
          ),
          child: Row(
            children: [
              // Edit answers
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: () => Navigator.pop(context),
                  icon: const Icon(Icons.edit_rounded, size: 16),
                  label: const Text('Edit'),
                  style: OutlinedButton.styleFrom(
                    foregroundColor: AppTheme.textSecondary,
                    side: const BorderSide(color: AppTheme.surface),
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(14),
                    ),
                  ),
                ),
              ),
              const SizedBox(width: 8),
              // Download PDF
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: () => _downloadPdf(plan),
                  icon: const Icon(
                    Icons.picture_as_pdf_rounded,
                    size: 16,
                    color: AppTheme.accent,
                  ),
                  label: const Text(
                    'Save PDF',
                    style: TextStyle(color: AppTheme.accent),
                  ),
                  style: OutlinedButton.styleFrom(
                    foregroundColor: AppTheme.accent,
                    side: const BorderSide(color: AppTheme.accent),
                    padding: const EdgeInsets.symmetric(vertical: 14),
                    shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(14),
                    ),
                  ),
                ),
              ),
              const SizedBox(width: 8),
              // Regenerate
              Expanded(
                child: ElevatedButton.icon(
                  onPressed: _regenerate,
                  icon: const Icon(
                    Icons.refresh_rounded,
                    color: Colors.white,
                    size: 16,
                  ),
                  label: const Text(
                    'Redo',
                    style: TextStyle(color: Colors.white),
                  ),
                  style: ElevatedButton.styleFrom(
                    padding: const EdgeInsets.symmetric(vertical: 14),
                  ),
                ),
              ),
            ],
          ),
        ),
      ],
    );
  }
}
